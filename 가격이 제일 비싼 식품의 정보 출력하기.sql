-- 방법 1. (정렬 후 뽑아오기)
SELECT *
FROM FOOD_PRODUCT
ORDER BY PRICE DESC
LIMIT 1

-- 방법 2. (서브쿼리)
SELECT *
FROM FOOD_PRODUCT
WHERE PRICE = (SELECT MAX(PRICE)
     FROM  FOOD_PRODUCT)
   
   
-- 방법 3 (윈도우 함수 사용(랭크 함수 사용))
SELECT PRODUCT_ID, PRODUCT_NAME, PRODUCT_CD, CATEGORY, PRICE
FROM ( SELECT PRODUCT_ID, PRODUCT_NAME, PRODUCT_CD, CATEGORY, PRICE, 
      RANK() OVER (ORDER BY PRICE DESC) AS RNK  # 가격(PRICE)이 높은 순서대로 전체 데이터의 순위를 매겨라
      FROM FOOD_PRODUCT ) AS RANKED_FOOD
WHERE RNK = 1
