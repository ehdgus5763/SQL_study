문제: FISH_NAME_INFO에서 물고기의 종류 별 물고기의 이름과 잡은 수를 출력하는 SQL문을 작성해주세요.
물고기의 이름 컬럼명은 FISH_NAME, 잡은 수 컬럼명은 FISH_COUNT로 해주세요.
결과는 잡은 수 기준으로 내림차순 정렬해주세요.




# 방법 1. JOIN + GROUP BY
SELECT  COUNT(*) AS FISH_COUNT, B.FISH_NAME AS FISH_NAME
FROM FISH_INFO A JOIN FISH_NAME_INFO B
ON A.FISH_TYPE = B.FISH_TYPE
GROUP BY A.FISH_TYPE, B.FISH_NAME
ORDER BY FISH_COUNT DESC


# 방법 2. 서브쿼리로 사전 집계 후 조인
SELECT 
    C.FISH_COUNT,
    N.FISH_NAME
FROM (
    SELECT 
        FISH_TYPE,
        COUNT(*) AS FISH_COUNT
    FROM 
        FISH_INFO
    GROUP BY 
        FISH_TYPE
) C
JOIN 
    FISH_NAME_INFO N ON C.FISH_TYPE = N.FISH_TYPE
ORDER BY 
    C.FISH_COUNT DESC;
