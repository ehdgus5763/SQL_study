문제: USED_GOODS_BOARD 테이블에서 2022년 10월 5일에 등록된 중고거래 게시물의 게시글 ID, 작성자 ID, 게시글 제목, 가격, 거래상태를 조회하는 SQL문을 작성해주세요.
     거래상태가 SALE 이면 판매중, RESERVED이면 예약중, DONE이면 거래완료 분류하여 출력해주시고, 결과는 게시글 ID를 기준으로 내림차순 정렬해주세요.

# 방법 1. CASE문 사용
SELECT BOARD_ID, WRITER_ID, TITLE, PRICE, 
CASE 
   WHEN STATUS = 'SALE' THEN '판매중' 
   WHEN STATUS = 'RESERVED' THEN '예약중'
ELSE '거래완료' END AS STATUS
FROM USED_GOODS_BOARD
WHERE CREATED_DATE = '2022-10-05'
ORDER BY BOARD_ID DESC

  
# 방법 2. 날짜 포맷 함수(DATE_FORMAT) 명시 + CASE 문
SELECT BOARD_ID, WRITER_ID, TITLE, PRICE, 
CASE 
   WHEN STATUS = 'SALE' THEN '판매중' 
   WHEN STATUS = 'RESERVED' THEN '예약중'
ELSE '거래완료' END AS STATUS
FROM USED_GOODS_BOARD
WHERE DATE_FORMAT(CREATED_DATE,'%Y-%m-%d') = '2022-10-05'
ORDER BY BOARD_ID DESC

  
# 방법 3. IF(조건, 참일 때, 거짓일 때) 함수를 중첩해서 작성하는 방법
SELECT BOARD_ID, WRITER_ID, TITLE, PRICE, 
IF(STATUS = 'SALE', '판매중',  IF(STATUS = 'RESERVED', '예약중', '거래완료') ) AS STATUS
FROM USED_GOODS_BOARD
WHERE CREATED_DATE = '2022-10-05'
ORDER BY BOARD_ID DESC
