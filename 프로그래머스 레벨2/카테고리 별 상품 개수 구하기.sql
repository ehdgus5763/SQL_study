문제:PRODUCT 테이블에서 상품 카테고리 코드(PRODUCT_CODE 앞 2자리) 별 상품 개수를 출력하는 SQL문을 작성해주세요. 
  결과는 상품 카테고리 코드를 기준으로 오름차순 정렬해주세요.

# 방법 1. 서브쿼리 활용 
SELECT CODE, COUNT(CODE) AS COUNT
FROM (SELECT LEFT(PRODUCT_CODE,2) AS CODE
      FROM PRODUCT) A
GROUP BY CODE

# 방법 2. SUBSTRING() / SUBSTR() 함수 활용
SELECT 
    SUBSTRING(PRODUCT_CODE, 1, 2) AS CATEGORY,
    COUNT(*) AS PRODUCTS
FROM 
    PRODUCT
GROUP BY 
    CATEGORY
ORDER BY 
    CATEGORY ASC

# 방법 3. LEFT() 함수 활용
SELECT 
    LEFT(PRODUCT_CODE, 2) AS CATEGORY,
    COUNT(*) AS PRODUCTS
FROM 
    PRODUCT
GROUP BY 
    LEFT(PRODUCT_CODE, 2)
ORDER BY 
    CATEGORY ASC

